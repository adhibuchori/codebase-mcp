import { expect, test } from 'bun:test';
import type { RouteDef } from '../../core/model/domain.types.ts';
import type { LanguagePack } from '../../core/model/language-pack.types.ts';
import { FLAG_GENERATED, FLAG_TEST } from '../../core/rank/classify.ts';
import type { LanguageRegistry, SymbolParser } from '../../ports/runtime.ts';
import { analyzeFile } from '../analyze-file.ts';

const ROUTE: RouteDef = {
  kind: 'http',
  role: 'handler',
  method: 'GET',
  pattern: '/x',
  line: 1,
  framework: 'test',
};

const pack: LanguagePack = {
  id: 'toy',
  name: 'Toy',
  tier: 3,
  extensions: ['.toy'],
  routeExtractors: [
    () => [ROUTE],
    () => {
      throw new Error('extractor bug');
    },
  ],
};

const languages: LanguageRegistry = {
  forPath: (path) => (path.endsWith('.toy') ? pack : undefined),
  all: () => [pack],
  parseTrace: () => null,
};

const parser: SymbolParser = {
  parse: async () => [
    { name: 'main', kind: 'function', line: 1, endLine: 2, container: '', signature: 'fn main' },
  ],
};

test('a source file gets symbols and routes; a failing extractor only loses its own routes', async () => {
  const analysis = await analyzeFile('src/app.toy', 'fn main\nend\n', { languages, parser });
  expect(analysis).toEqual({
    lang: 'toy',
    lines: 2,
    flags: 0,
    symbols: [
      { name: 'main', kind: 'function', line: 1, endLine: 2, container: '', signature: 'fn main' },
    ],
    routes: [ROUTE],
  });
});

test('unknown, generated and minified files are indexed for search only', async () => {
  expect(await analyzeFile('data/values.csv', '', { languages, parser })).toEqual({
    lang: 'text',
    lines: 0,
    flags: 0,
    symbols: [],
    routes: [],
  });
  const generated = await analyzeFile(
    'src/gen.toy',
    '// Code generated by protoc. DO NOT EDIT.\nfn x',
    { languages, parser },
  );
  expect(generated.flags & FLAG_GENERATED).toBe(FLAG_GENERATED);
  expect(generated.symbols).toEqual([]);
  expect(
    (await analyzeFile('src/min.toy', 'x'.repeat(5000), { languages, parser })).symbols,
  ).toEqual([]);
  expect(
    (await analyzeFile('test/app.toy', 'fn main', { languages, parser })).flags & FLAG_TEST,
  ).toBe(FLAG_TEST);
});
