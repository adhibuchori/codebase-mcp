import { describe, expect, test } from 'bun:test';
import {
  classifyPath,
  FLAG_DOCS,
  FLAG_GENERATED,
  FLAG_TEST,
  FLAG_VENDOR,
  flagLabels,
  hasGeneratedHeader,
} from '../classify.ts';

describe('classifyPath', () => {
  test.each([
    ['src/test/java/OrderServiceTest.java', FLAG_TEST],
    ['internal/payment/service_test.go', FLAG_TEST],
    ['src/app.spec.ts', FLAG_TEST],
    ['tests/test_orders.py', FLAG_TEST],
    ['spec/models/order_spec.rb', FLAG_TEST],
    ['api/orders.pb.go', FLAG_GENERATED],
    ['src/generated/client.ts', FLAG_GENERATED],
    ['public/app.min.js', FLAG_GENERATED],
    ['vendor/github.com/x/y.go', FLAG_VENDOR],
    ['docs/architecture.md', FLAG_DOCS],
    ['README.md', FLAG_DOCS],
    ['src/main/java/OrderService.java', 0],
  ])('%s', (path, flags) => {
    expect(classifyPath(path)).toBe(flags);
  });

  test('flags combine', () => {
    expect(classifyPath('vendor/lib/x_test.go')).toBe(FLAG_TEST | FLAG_VENDOR);
  });
});

test('hasGeneratedHeader', () => {
  expect(hasGeneratedHeader('// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x')).toBe(
    true,
  );
  expect(hasGeneratedHeader('/* @generated */')).toBe(true);
  expect(hasGeneratedHeader('package main\n')).toBe(false);
});

test('flagLabels', () => {
  expect(flagLabels(FLAG_TEST | FLAG_GENERATED | FLAG_VENDOR | FLAG_DOCS)).toEqual([
    'test',
    'generated',
    'vendor',
    'docs',
  ]);
  expect(flagLabels(0)).toEqual([]);
});
