#!/usr/bin/env bun
/**
 * Refreshes assets/grammars/*.wasm and assets/queries/*.scm from the npm packages pinned in
 * grammars.ts, and records each file's SHA-256 in assets/grammars/manifest.json. Run it after
 * changing a version; commit the result. Needs npm and tar (both ship with Node and Windows 10+).
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { GRAMMARS } from './grammars.ts';

const root = join(import.meta.dirname, '..', '..');
const grammarsDir = join(root, 'assets', 'grammars');
const queriesDir = join(root, 'assets', 'queries');
const work = mkdtempSync(join(tmpdir(), 'codebase-mcp-grammars-'));
const unpacked = new Map<string, string>();

/** Downloads and unpacks one package version once; returns its folder. */
function unpack(pkg: string, version: string): string {
  const key = `${pkg}@${version}`;
  const known = unpacked.get(key);
  if (known) return known;
  const target = join(work, key.replaceAll('/', '_'));
  mkdirSync(target, { recursive: true });
  const output = execFileSync('npm', ['pack', key, '--silent', '--pack-destination', target], {
    encoding: 'utf8',
    shell: process.platform === 'win32',
  });
  const tarball = join(target, output.trim().split('\n').at(-1) ?? '');
  execFileSync('tar', ['-xzf', tarball, '-C', target]);
  const folder = join(target, 'package');
  unpacked.set(key, folder);
  return folder;
}

const sha256 = (path: string): string =>
  createHash('sha256').update(readFileSync(path)).digest('hex');

mkdirSync(grammarsDir, { recursive: true });
mkdirSync(queriesDir, { recursive: true });
const manifest: Record<string, { pkg: string; version: string; sha256: string; query: string }> =
  {};
try {
  for (const grammar of GRAMMARS) {
    const wasmTarget = join(grammarsDir, `${grammar.id}.wasm`);
    cpSync(join(unpack(grammar.pkg, grammar.version), grammar.wasm), wasmTarget);
    const queryTarget = join(queriesDir, `${grammar.id}.scm`);
    if (grammar.queries.length > 0) {
      const text = grammar.queries
        .map((query) => readFileSync(join(unpack(query.pkg, query.version), query.path), 'utf8'))
        .join('\n');
      writeFileSync(
        queryTarget,
        `; Generated by scripts/grammars/sync.ts from ${grammar.queries.map((q) => `${q.pkg}@${q.version}`).join(' + ')}\n${text}`,
      );
    } else if (!existsSync(queryTarget)) {
      throw new Error(
        `${grammar.id} has no packaged tags query and assets/queries/${grammar.id}.scm is missing`,
      );
    }
    manifest[grammar.id] = {
      pkg: grammar.pkg,
      version: grammar.version,
      sha256: sha256(wasmTarget),
      query: grammar.queries.length > 0 ? 'packaged' : 'own',
    };
    console.log(`✓ ${grammar.id} (${grammar.pkg}@${grammar.version})`);
  }
  writeFileSync(join(grammarsDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
